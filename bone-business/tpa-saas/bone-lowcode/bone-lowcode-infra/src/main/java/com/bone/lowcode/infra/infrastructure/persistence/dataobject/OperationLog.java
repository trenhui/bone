    private Long objectId;

    /**
     * 操作对象类型
     */
    private Byte objectType;

    /**
     * 操作描述
     */
    private String operation;

    /**
     * 修改前值
     */
    private String beforeValue;

    /**
     * 修改后值
     */
    private String afterValue;

    /**
     * 创建人
     */
    private String createBy;

