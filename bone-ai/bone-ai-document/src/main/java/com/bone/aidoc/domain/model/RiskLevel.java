package com.bone.aidoc.domain.model;

/**
 * 字段风险等级（ADR-0046 §四：不同字段/票种/风险等级应分别标定阈值，禁止全局 0.95）。
 *
 * <p>用于驱动 {@link ReviewPolicy} 的差异化放行：金额、证件号、日期等高风险字段需要更严格的 置信度与质量门槛，普通文本字段可放宽。
 */
public enum RiskLevel {
  /** 低风险（普通文本、机构名称等）。 */
  LOW,
  /** 中风险（地址、诊断描述等）。 */
  MEDIUM,
  /** 高风险（日期、证件号、发票代码等）。 */
  HIGH,
  /** 极高风险（金额、赔付额、个人支付额等直接涉钱字段）。 */
  CRITICAL
}
