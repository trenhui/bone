-- synap-claim 第十五批 DDL 变更：目录准入（缺口 ① 费用明细筛选 / 适用限定「药品·诊疗」维度）
--
-- 背景：V1 §3.5 的费用明细筛选要求"合理金额须在保障目录内"，适用限定（§2 要素 6）也含
--       「药品 / 诊疗」两维。现状是三层同时缺位：
--       ① t_adj_liability 没有目录相关列 ⇒ 业务上"只保目录内药品"这类责任根本表达不出来；
--       ② 引擎里本就没有目录判定 —— 明细的 item_code 落了库，但从未参与任何筛选；
--       ③ 结果：条款有约定、系统照全额赔，且配置页 / 文档 / 评审三处都显示"已支持"。
--       与 Q-05 日限额、V14 适用限定同一类缺口：「配了不生效」。
--
-- 为什么不在本库建一张目录表：
--       目录是外部主数据（医保局 / 再保 / 接入方维护），有独立版本节奏与生效期。
--       在本库放副本会立刻产生"两个真源"：谁新谁旧说不清，出事时无法回答"当时按哪一版判的"。
--       故本仓库只定义查询端口（ItemCatalogPort）与 fail-closed 行为，目录数据由接入方提供；
--       同时**不新增表**——§9.5 的 35 张表口径保持不变。
--
-- 为什么必须成对配置（金额与口径同理）：
--       只配 catalog_code 不开策略 ⇒ 编码永远不会被查询（配了不生效 ⇒ 超赔）；
--       只开策略不配 catalog_code ⇒ 不知道该查哪一版（查任何一版都是猜）。
--       两种都在装载期被 CatalogAdmission#of 拒绝，而不是回落到"当作全在目录内"。
--
-- 为什么默认 NONE 而不是 MANDATORY：
--       历史责任配置必须保持既有行为（F1 双轨回归绿）。默认 MANDATORY 会让存量责任在目录端口
--       未接入时全部退补件——那是把缺口从"静默超赔"换成"全量停摆"，同样不可接受。
--       缺省不查目录，是"与引入本机制之前逐字一致"的唯一选择；未配的责任逐条留在缺口清单里可见。

ALTER TABLE t_adj_liability
  ADD COLUMN catalog_policy VARCHAR(16) NOT NULL DEFAULT 'NONE'
    COMMENT '目录准入策略(缺口①/适用限定药品·诊疗)：NONE=不查目录(与历史一致) / MANDATORY=每条明细必须查到结论，查不到即退补件'
    AFTER limit_diagnosis_codes,
  ADD COLUMN catalog_code VARCHAR(64) NOT NULL DEFAULT ''
    COMMENT '目录编码(如 NATIONAL_2024)：按哪一版目录判定；策略为 NONE 时必须为空（配了不会被查询，装载期拒绝）'
    AFTER catalog_policy;
