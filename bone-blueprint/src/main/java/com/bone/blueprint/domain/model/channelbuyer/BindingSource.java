package com.bone.blueprint.domain.model.channelbuyer;

/**
 * 渠道买家映射的绑定来源。
 *
 * <p><b>为何要区分来源，而不是一个 bound 布尔</b>：拉单时自动建出来的映射（影子）与运营手工绑定的映射，<strong>可信度完全不同</strong>。
 * 影子映射只是「见过这个渠道买家」的记录，{@code customerId = 0}；把它和人工绑定混在一起，运营在列表里无法区分「这个客户是真的对上了」还是
 * 「系统还没绑」。客服与对账都依赖这个区分。
 */
public enum BindingSource {

  /** 人工绑定：运营把渠道买家指到某个内部客户上。 */
  MANUAL,

  /**
   * 自动影子：拉单时发现该渠道买家尚无映射而自动登记一条待绑定记录。
   *
   * <p>影子映射<strong>不是</strong>「已识别的客户」——它只保证「同一渠道买家第二次下单时订单维度稳定」， 并为后续人工/规则绑定提供候选清单。
   */
  AUTO_SHADOW
}
